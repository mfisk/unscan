/// Per-font feature for a single character.
#[derive(Debug, Clone)]
pub struct FontCharEntry {
    pub font_name: String,
    pub features: CharFeatures,
}

/// The full index: for each indexed character, a list of (font, features)
/// plus flat per-character vectors for brute-force spatial lookup.
#[derive(Debug)]
pub struct CharIndex {
    /// char → Vec<(font_name, features)> — raw entries for serialization + merge
    pub entries: HashMap<char, Vec<FontCharEntry>>,
    /// Fonts that were scanned but produced no indexable characters.
    pub skipped_fonts: std::collections::HashSet<String>,
    /// Per-font metadata (font_key → FontMeta). Serialized with the index
    /// so we can skip the filesystem font scan on warm runs.
    pub font_meta: HashMap<String, FontMeta>,
    /// Ordered font name table: font_id → font_name
    pub font_names_table: Vec<String>,
    /// Per-character per-dimension standard deviations (for diagnostics)
    dim_sigmas: HashMap<char, Vec<f32>>,
}

impl CharIndex {
    /// Build flat per-character vectors and compute per-dimension σ from entries.
    pub fn rebuild_vecs(
        &mut self,
        classifier: &mut dyn crate::classifier::Classifier,
        render_params: &crate::char_render::RenderParams,
    ) {
        // Build font name → id mapping
        let mut name_set: std::collections::HashSet<&str> = std::collections::HashSet::new();
        for entries in self.entries.values() {
            for e in entries {
                name_set.insert(&e.font_name);
            }
        }
        let mut names: Vec<String> = name_set.into_iter().map(|s| s.to_string()).collect();
        names.sort();
        self.font_names_table = names;
        let name_to_id: HashMap<&str, usize> = self.font_names_table.iter()
            .enumerate()
            .map(|(i, n)| (n.as_str(), i))
            .collect();

        // When the classifier needs rasters, pre-load fonts so we can
        // re-render (cache-backed) the glyphs that were not serialized.
        let want_raster = classifier.needs_raster();
        let mut font_cache: HashMap<String, Option<ab_glyph::FontVec>> = HashMap::new();
        if want_raster {
            for (font_name, meta) in &self.font_meta {
                let loaded = std::fs::read(&meta.path).ok().and_then(|data| {
                    let mut fv = ab_glyph::FontVec::try_from_vec(data).ok()?;
                    if let Some(ref vars) = meta.variations {
                        use ab_glyph::VariableFont;
                        for &(ref tag, val) in vars {
                            fv.set_variation(tag, val);
                        }
                    }
                    Some(fv)
                });
                font_cache.insert(font_name.clone(), loaded);
            }
        }

        self.dim_sigmas.clear();

        // Feed font vectors into the classifier and compute dim_sigmas
        for (c, char_entries) in &mut self.entries {
            if char_entries.is_empty() {
                continue;
            }

            for e in char_entries.iter_mut() {
                if let Some(&font_id) = name_to_id.get(e.font_name.as_str()) {
                    // Populate raster from render cache if needed and missing
                    if want_raster && e.features.raster.is_none() {
                        if let Some(Some(font)) = font_cache.get(&e.font_name) {
                            let overrides = self.font_meta.get(&e.font_name)
                                .and_then(|m| m.glyph_overrides.as_ref())
                                .and_then(|ovs| ovs.iter().find(|(ch, _)| *ch == *c))
                                .map(|&(_, gid)| ab_glyph::GlyphId(gid));
                            if let Some(img) = crate::char_render::get_rendered_char(
                                font, &e.font_name, *c, overrides, render_params,
                            ) {
                                e.features.raster = Some(img);
                            }
                        }
                    }
                    classifier.add_font(font_id, *c, &e.features);
                }
            }

            // Compute per-dimension σ from raw features (for diagnostics)
            let feat_dim = FEAT_LEN;
            let n = char_entries.len() as f32;
            let mut means = vec![0.0f32; feat_dim];
            for e in char_entries.iter() {
                let raw = e.features.as_slice();
                for d in 0..feat_dim {
                    means[d] += raw[d];
                }
            }
            for d in 0..feat_dim { means[d] /= n; }

            let mut sigmas = vec![0.0f32; feat_dim];
            for e in char_entries.iter() {
                let raw = e.features.as_slice();
                for d in 0..feat_dim {
                    let diff = raw[d] - means[d];
                    sigmas[d] += diff * diff;
                }
            }
            for d in 0..feat_dim { sigmas[d] = (sigmas[d] / n).sqrt(); }
            self.dim_sigmas.insert(*c, sigmas);
        }
    }

    /// Populate font_meta from a font catalog so the index can skip filesystem
    /// scans on warm runs.  Replaces any existing metadata.
    pub fn populate_font_meta(&mut self, catalog: &[crate::font_scan::FontEntry]) {
        for fe in catalog {
            let class_u8 = match fe.class {
                crate::font_scan::FontClass::Serif => 0,
                crate::font_scan::FontClass::Sans => 1,
                crate::font_scan::FontClass::Mono => 2,
                crate::font_scan::FontClass::Unknown => 3,
            };
            self.font_meta.insert(fe.font_key(), FontMeta {
                path: fe.path.clone(),
                family_name: fe.family_name.clone(),
                postscript_name: fe.postscript_name.clone(),
                is_bold: fe.is_bold,
                is_italic: fe.is_italic,
                class: class_u8,
                variant_tag: fe.variant_tag.clone(),
                glyph_overrides: fe.glyph_overrides.clone(),
                oldstyle_figures: fe.oldstyle_figures,
                variations: fe.variations.clone(),
            });
        }
    }
}

/// Build the per-character index for all provided fonts.
/// Glyph override map for OT variant entries (e.g. smcp, onum).
/// Maps character → overridden glyph ID so the CI renders the correct variant glyph.
pub type GlyphOverrides = Option<Vec<(char, u16)>>;

/// Variable-font axis coordinates to apply before rendering.
pub type Variations = Option<Vec<([u8; 4], f32)>>;

/// Metadata for a single font entry (one per font_key in the catalog).
/// Stored in the char index so we can skip the filesystem scan on warm runs.
#[derive(Debug, Clone)]
pub struct FontMeta {
    pub path: std::path::PathBuf,
    pub family_name: String,
    pub postscript_name: String,
    pub is_bold: bool,
    pub is_italic: bool,
    pub class: u8, // 0=Serif, 1=Sans, 2=Mono, 3=Unknown
    pub variant_tag: String,
    pub glyph_overrides: GlyphOverrides,
    pub oldstyle_figures: bool,
    pub variations: Variations,
}

/// Resolve glyph ID for a character, applying OT variant overrides when present.
/// Falls back to the font's default cmap lookup if no override exists for this character.
pub fn resolve_glyph<F: ab_glyph::Font>(font: &F, ch: char, overrides: Option<&[(char, u16)]>) -> ab_glyph::GlyphId {
    if let Some(ovs) = overrides {
        if let Some(&(_, gid)) = ovs.iter().find(|(c, _)| *c == ch) {
            return ab_glyph::GlyphId(gid);
        }
    }
    font.glyph_id(ch)
}

pub fn build_char_index(
    font_paths: &[(String, std::path::PathBuf, GlyphOverrides, Variations)],
    classifier: &mut dyn crate::classifier::Classifier,
    render_params: &crate::char_render::RenderParams,
) -> CharIndex {
    use rayon::prelude::*;

    let chars = indexed_chars();

    // Per-font result: Vec of (char, entry) pairs, plus font_name if skipped.
    struct FontResult {
        char_entries: Vec<(char, FontCharEntry)>,
        skipped: Option<String>,
    }

    // Phase 1: process each font in parallel (CPU-bound: render + features).
    // Font bytes are loaded from disk per-thread and dropped after processing,
    // so only ~N fonts are in memory at once (N = rayon thread count).
    let results: Vec<FontResult> = font_paths.par_iter().map(|(font_name, font_path, glyph_overrides, variations)| {
        let font_data = match std::fs::read(font_path) {
            Ok(d) => d,
            Err(_) => {
                return FontResult {
                    char_entries: Vec::new(),
                    skipped: Some(font_name.clone()),
                };
            }
        };
        let mut font = match FontRef::try_from_slice(&font_data) {
            Ok(f) => f,
            Err(_) => {
                return FontResult {
                    char_entries: Vec::new(),
                    skipped: Some(font_name.clone()),
                };
            }
        };

        // Apply variable-font axis coordinates (e.g. wght=700 for Bold)
        if let Some(vars) = variations {
            use ab_glyph::VariableFont;
            for (tag, value) in vars {
                font.set_variation(tag, *value);
            }
        }

        // Build fast lookup for glyph overrides
        let override_map: HashMap<char, u16> = glyph_overrides
            .as_ref()
            .map(|v| v.iter().cloned().collect())
            .unwrap_or_default();

        let mut char_entries = Vec::with_capacity(chars.len());
        for &c in chars {
            let glyph_override = override_map.get(&c).map(|&gid| ab_glyph::GlyphId(gid));
            let img = crate::char_render::get_rendered_char(
                &font, font_name, c, glyph_override, render_params,
            );
            if let Some(img) = img {
                if let Some(mut feats) = compute_features(&img) {
                    feats.raster = Some(img);
                    char_entries.push((c, FontCharEntry {
                        font_name: font_name.clone(),
                        features: feats,
                    }));
                }
            }
        }

        let skipped = if char_entries.is_empty() { Some(font_name.clone()) } else { None };
        FontResult { char_entries, skipped }
    }).collect();

    // Phase 2: merge results (sequential, fast — just moving Vecs)
    let mut entries: HashMap<char, Vec<FontCharEntry>> = HashMap::new();
    for c in chars {
        entries.insert(*c, Vec::with_capacity(font_paths.len()));
    }
    let mut skipped_fonts: std::collections::HashSet<String> = std::collections::HashSet::new();

    for result in results {
        if let Some(name) = result.skipped {
            skipped_fonts.insert(name);
        }
        for (c, entry) in result.char_entries {
            entries.entry(c).or_default().push(entry);
        }
    }

    let mut index = CharIndex {
        entries,
        skipped_fonts,
        font_meta: HashMap::new(),
        font_names_table: Vec::new(),
        dim_sigmas: HashMap::new(),
    };
    index.rebuild_vecs(classifier, render_params);
    index
}





