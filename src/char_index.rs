/// Crop an image to its ink bounds (with 1px padding) and resize so the height
/// equals `NORM_H`, preserving aspect ratio. Used by scan-time extraction to
/// match the geometry of index-time rendering (tight ink crop, 1px padding,
/// NORM_H height).
///
/// Ink threshold matches `compute_features` (pixel < 200 = ink).
/// Crop a word image to its ink bounds with 1px padding.
/// Unlike `normalize_to_ink_bounds`, this does NOT rescale — it returns the
/// cropped image at original resolution so seam carving works on real pixels.
fn normalize_word_to_ink(img: &GrayImage) -> Option<GrayImage> {
    let (w, h) = img.dimensions();
    if w == 0 || h == 0 {
        return None;
    }
    const THRESH: u8 = 200;
    let mut min_x = w;
    let mut max_x = 0u32;
    let mut min_y = h;
    let mut max_y = 0u32;
    for y in 0..h {
        for x in 0..w {
            if img.get_pixel(x, y).0[0] < THRESH {
                if x < min_x { min_x = x; }
                if x > max_x { max_x = x; }
                if y < min_y { min_y = y; }
                if y > max_y { max_y = y; }
            }
        }
    }
    if min_x > max_x || min_y > max_y {
        return None;
    }
    let pad = 1u32;
    let crop_x = min_x.saturating_sub(pad);
    let crop_y = min_y.saturating_sub(pad);
    let crop_w = (max_x + pad + 1).min(w) - crop_x;
    let crop_h = (max_y + pad + 1).min(h) - crop_y;
    if crop_w < 2 || crop_h < 2 {
        return None;
    }
    Some(image::imageops::crop_imm(img, crop_x, crop_y, crop_w, crop_h).to_image())
}

pub fn normalize_to_ink_bounds(img: &GrayImage) -> Option<GrayImage> {
    let (w, h) = img.dimensions();
    if w == 0 || h == 0 {
        return None;
    }
    const THRESH: u8 = 200;
    let mut min_x = w;
    let mut max_x = 0u32;
    let mut min_y = h;
    let mut max_y = 0u32;
    for y in 0..h {
        for x in 0..w {
            if img.get_pixel(x, y).0[0] < THRESH {
                if x < min_x { min_x = x; }
                if x > max_x { max_x = x; }
                if y < min_y { min_y = y; }
                if y > max_y { max_y = y; }
            }
        }
    }
    if min_x > max_x || min_y > max_y {
        return None;
    }
    // Crop tightly to ink, then paste onto a white canvas with guaranteed
    // 1px padding on all sides — matching index-time render_char_normalised
    // which creates a canvas of (ink_w+2) × (ink_h+2).
    // Previous approach used saturating_sub which clipped at image boundary,
    // producing 0px padding when ink reached the edge of the raw slice.
    let ink_w = max_x - min_x + 1;
    let ink_h = max_y - min_y + 1;
    if ink_w < 1 || ink_h < 1 {
        return None;
    }
    let pad = 1u32;
    let canvas_w = ink_w + 2 * pad;
    let canvas_h = ink_h + 2 * pad;
    let mut canvas = GrayImage::from_pixel(canvas_w, canvas_h, Luma([255u8]));
    // Copy ink region into canvas at (pad, pad)
    for y in min_y..=max_y {
        for x in min_x..=max_x {
            let px = img.get_pixel(x, y);
            canvas.put_pixel(x - min_x + pad, y - min_y + pad, *px);
        }
    }
    let scaled_w = (canvas_w as f32 * NORM_H as f32 / canvas_h as f32).ceil() as u32;
    if scaled_w < 2 {
        return None;
    }
    Some(image::imageops::resize(
        &canvas,
        scaled_w,
        NORM_H,
        image::imageops::FilterType::Lanczos3,
    ))
}

