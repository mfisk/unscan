/// Search result from the character index for a single character.
/// Contains font candidates within the tolerance radius.
#[derive(Debug, Clone)]
pub struct CharSearchResult {
    /// The character queried
    pub ch: char,
    /// Candidate fonts within tolerance: (font_name, cosine_similarity)
    pub candidates: Vec<(String, f32)>,
    /// The search radius used
    pub radius: f32,
    /// Number of fonts within the radius
    pub n_within_radius: usize,
}

/// Search the index for candidate fonts matching the given character crops.
///
/// This is the single shared search function used by both the pipeline and tests.
///
/// # Scoring: geometric mean of per-character distances
///
/// Each character's nearest-neighbor search gives us a squared Euclidean distance d²ᵢ for
/// font F in the 57-dimensional weighted feature space.  Under the null
/// hypothesis (random font), these distances follow a scaled χ² distribution
/// — fonts that are genuinely similar will have consistently small distances
/// across multiple independent character observations.
///
/// We aggregate via the **geometric mean of distances**:
///
/// ```text
///     score(F) = exp( (1/N) · Σᵢ log(d²ᵢ + ε) )
/// ```
///
/// This is equivalent to multiplying per-character p-values (Fisher's method)
/// in log space.  It has two key properties:
///
/// 1. **Multiplicative sensitivity:** a font that's close on 14 of 15 chars
///    but far on 1 gets a much worse score than a font that's moderately close
///    on all 15.  One bad character tanks the geometric mean — this naturally
///    penalizes the "619 fonts within 2× on 'e'" problem because those fonts
///    will have large distances on other characters.
///
/// 2. **No arbitrary union:** we don't union per-character candidate sets.
///    Instead, we collect (font_id, d²) pairs per character, then score every
///    font that appears in ≥ quorum characters.  Fonts appearing in only 1-2
///    character neighborhoods are discarded — they're statistical noise.
///
/// The quorum threshold (currently ≥ 50% of queried characters) acts as a
/// lightweight pre-filter before the geometric mean calculation.  A font must
/// be a plausible match on at least half the characters to be considered.
///
/// Returns top `top_n` fonts by geometric-mean distance (ascending = best).
/// The returned f32 score is negated log-geometric-mean so that higher = better,
/// matching the convention expected by downstream callers.
/// Per-character CI detail, collected from the real search_candidates loop.
#[derive(Debug, Clone)]
pub struct CharCiDetail {
    pub ch: char,
    pub crop_index: usize,
    pub min_dist_sq: f32,
    pub passed_gate: bool,
    /// Top-3 nearest fonts (name, dist_sq).
    pub nearest: Vec<(String, f32)>,
    /// When the OCR correction gate fires, the original OCR character
    /// that was replaced.  `ch` then holds the corrected character,
    /// and `nearest`/`min_dist_sq` reflect the corrected char's CI.
    pub ocr_corrected_from: Option<char>,
    /// Best alternative character considered (even if correction gate
    /// didn't fire).  Always the char with the lowest distance among
    /// all confusables/alternatives tested, if any were tested.
    pub best_alt_char: Option<char>,
    /// Distance of the best alternative character.
    pub best_alt_dist: Option<f32>,
}

/// Result of `search_candidates`: ranked font scores + per-character CI detail.
#[derive(Debug)]
pub struct CiSearchResult {
    pub scores: Vec<(String, f32)>,
    pub char_detail: Vec<CharCiDetail>,
}

pub fn search_candidates(
    index: &CharIndex,
    char_crops: &[(char, GrayImage)],
    thoroughness: f32,
    audit: bool,
    classifier: &dyn crate::classifier::Classifier,
) -> CiSearchResult {
    if char_crops.is_empty() {
        return CiSearchResult { scores: Vec::new(), char_detail: Vec::new() };
    }

    // Pre-compute weighted feature vectors for all crops
    let feat_t0 = std::time::Instant::now();
    let crop_feats: Vec<(usize, char, Vec<f32>)> = char_crops
        .iter()
        .enumerate()
        .filter_map(|(i, (c, img))| {
            compute_features(img).map(|f| (i, *c, classifier.prepare(*c, &f)))
        })
        .collect();
    let feat_us = feat_t0.elapsed().as_micros();

    if crop_feats.is_empty() {
        return CiSearchResult { scores: Vec::new(), char_detail: Vec::new() };
    }

    let n_chars = crop_feats.len();
    // Quorum: font must appear in at least half the character neighborhoods.
    let _quorum = ((n_chars + 1) / 2).max(1) as f32 / thoroughness;
    let _quorum = (_quorum.ceil() as usize).max(1);


    // For each character, find nearby fonts and record their distances.
    // font_id → Vec<(log_dist, weight)>
    let mut font_log_dists: HashMap<usize, Vec<(f32, f32)>> = HashMap::new();
    // Track which gated crops each font appeared in (for second-pass real-distance lookup)
    let mut font_gated_hits: HashMap<usize, HashSet<usize>> = HashMap::new();
    // Collect crop info for gated crops so we can compute real distances in second pass
    let mut gated_crops: Vec<(char, Vec<f32>, f32)> = Vec::new(); // (score_ch, query_feat, weight)
    let mut quality_gate_pass = 0usize;
    let mut quality_gate_fail = 0usize;
    let mut no_tree = 0usize;
    let mut char_detail: Vec<CharCiDetail> = Vec::with_capacity(crop_feats.len());

    let search_t0 = std::time::Instant::now();
    let mut brute_us: u64 = 0;
    let mut alt_us: u64 = 0;
    for (crop_idx, c, query_feat) in &crop_feats {
        let weight = char_weight(*c);

        // Find nearest neighbor + everything within (2.5 × thoroughness)× that distance.
        let brute_t0 = std::time::Instant::now();
        let hits: Vec<(usize, f32)> = if let Some(points) = index.flat_vecs.get(c) {
            nearest_within_factor_brute(points, query_feat, 2.5 * thoroughness)
        } else {
            no_tree += 1;
            continue;
        };
        brute_us += brute_t0.elapsed().as_micros() as u64;

        let min_dist_sq = hits.iter().map(|(_, d)| *d).fold(f32::INFINITY, f32::min);

        // ── OCR correction gate ─────────────────────────────────────
        // If the OCR char's best distance is suspiciously large AND 10×
        // worse than the best distance under a different character, the
        // OCR label is likely mangled (e.g. Q→dingbat at 50-100×).
        // Substitute the alternative. Only fires for extreme mismatches,
        // not style confusion (e vs c at 2-5×).
        let mut effective_hits = hits;
        let mut effective_min = min_dist_sq;
        let mut effective_ch: Option<char> = None;
        let mut best_alt_char: Option<char> = None;
        let mut best_alt_dist: Option<f32> = None;

        let alt_t0 = std::time::Instant::now();
        if min_dist_sq > 0.1 {
            // Only check alternatives when OCR match is already poor.
            // Test confusable characters that OCR commonly swaps.
            let confusables: &[char] = match c {
                'l' | 'I' | '1' | '|' => &['l', 'I', '1'],
                'O' | '0' | 'Q' => &['O', '0', 'Q', 'o'],
                'o' | 'c' | 'e' => &['o', 'c', 'e'],
                'S' | '5' | 's' => &['S', '5', 's'],
                'B' | '8' => &['B', '8'],
                'Z' | '2' => &['Z', '2'],
                'b' | 'd' | 'p' | 'q' => &['b', 'd', 'p', 'q'],
                'n' | 'h' | 'u' => &['n', 'h', 'u', 'm', 'r'],
                _ => &[],
            };
            // Also check every indexed char if the distance is truly catastrophic
            let check_all = min_dist_sq > 0.5;
            let chars_to_check: Vec<char> = if check_all {
                indexed_chars().iter().filter(|&&alt| alt != *c).copied().collect()
            } else {
                confusables.iter().filter(|&&alt| alt != *c).copied().collect()
            };


            for alt_c in &chars_to_check {
                if let Some(alt_points) = index.flat_vecs.get(alt_c) {
                    let alt_hits = nearest_within_factor_brute(alt_points, query_feat, 2.5 * thoroughness);
                    let alt_min = alt_hits.iter().map(|(_, d)| *d).fold(f32::INFINITY, f32::min);
                    // Track best alt regardless of correction gate (audit only)
                    if audit && best_alt_dist.map_or(true, |d| alt_min < d) {
                        best_alt_char = Some(*alt_c);
                        best_alt_dist = Some(alt_min);
                    }
                    if alt_min < effective_min && min_dist_sq > alt_min * 10.0 {
                        effective_hits = alt_hits;
                        effective_min = alt_min;
                        effective_ch = Some(*alt_c);
                    }
                }
            }
        }
        alt_us += alt_t0.elapsed().as_micros() as u64;

        let hits = effective_hits;
        let min_dist_sq = effective_min;

        // Quality gate: scaled by thoroughness (default 0.5, higher = more permissive)
        let passed_gate = min_dist_sq <= 0.5 * thoroughness;
        if !passed_gate {
            quality_gate_fail += 1;
        } else {
            quality_gate_pass += 1;
        }

        // Collect per-char detail from the real search
        let mut sorted_hits = hits.clone();
        sorted_hits.sort_by(|a, b| a.1.partial_cmp(&b.1).unwrap_or(std::cmp::Ordering::Equal));
        let nearest: Vec<(String, f32)> = sorted_hits.iter()
            .take(3)
            .filter_map(|(font_id, d)| {
                let name = index.font_names_table.get(*font_id)?;
                Some((name.clone(), *d))
            })
            .collect();
        char_detail.push(CharCiDetail {
            ch: effective_ch.unwrap_or(*c),
            crop_index: *crop_idx,
            min_dist_sq,
            passed_gate,
            nearest,
            ocr_corrected_from: effective_ch.map(|_| *c),
            best_alt_char,
            best_alt_dist,
        });

        if !passed_gate {
            continue;
        }

        let score_ch = effective_ch.unwrap_or(*c);
        gated_crops.push((score_ch, query_feat.clone(), weight));
        let gated_idx = gated_crops.len() - 1;

        for (font_id, dist_sq) in &hits {
            let log_d = (dist_sq + 1e-10_f32).ln();
            font_log_dists.entry(*font_id).or_default().push((log_d, weight));
            font_gated_hits.entry(*font_id).or_default().insert(gated_idx);
        }
    }
    let search_us = search_t0.elapsed().as_micros();

    // ── Second pass: fill in real distances for candidate fonts that fell
    //    outside the search radius on some characters. ──────────────────
    //
    // The radius filter in nearest_within_factor_brute can exclude the
    // correct font when another font happens to land very close on that
    // character (tightening the radius).  Rather than fabricating a harsh
    // fixed penalty (log(1.0) = 0.0, ~100,000× worse than real distances),
    // we look up the font's actual distance from flat_vecs.
    let n_gated = gated_crops.len();
    let mut backfill_count = 0usize;
    for (font_id, hit_set) in &font_gated_hits {
        if hit_set.len() < n_gated {
            for (gi, (score_ch, qfeat, w)) in gated_crops.iter().enumerate() {
                if !hit_set.contains(&gi) {
                    if let Some(points) = index.flat_vecs.get(score_ch) {
                        // O(1) font_id lookup via prebuilt index (was linear scan)
                        let ref_vec_opt = index.flat_vecs_font_idx.get(score_ch)
                            .and_then(|idx_map| idx_map.get(font_id))
                            .map(|&idx| &points[idx].1);
                        if let Some(ref_vec) = ref_vec_opt {
                            let dist_sq = squared_distance(qfeat, ref_vec);
                            let log_d = (dist_sq + 1e-10_f32).ln();
                            font_log_dists.entry(*font_id).or_default().push((log_d, *w));
                            backfill_count += 1;
                        }
                    }
                }
            }
        }
    }
    if backfill_count > 0 {
        eprintln!("  CI: backfilled {} real distances for out-of-radius candidates", backfill_count);
    }

    eprintln!(
        "  CI: {} crops, {} pass gate, {} fail gate, {} no_tree → {} fonts in voting [feat={:.1}ms search={:.1}ms (brute={:.1}ms alt={:.1}ms) backfill={}]",
        crop_feats.len(),
        quality_gate_pass,
        quality_gate_fail,
        no_tree,
        font_log_dists.len(),
        feat_us as f64 / 1000.0,
        search_us as f64 / 1000.0,
        brute_us as f64 / 1000.0,
        alt_us as f64 / 1000.0,
        backfill_count,
    );

    // Aggregate: weighted geometric mean of distances per font.
    //
    // After the second pass, candidate fonts have real distances for all
    // characters they were within radius on PLUS actual distances for chars
    // they fell outside the radius on.  The fixed penalty below now only
    // fires for fonts that genuinely lack a glyph for a character (rare
    // for Latin text).
    let penalty_log_dist = 0.0_f32; // log(1.0); appropriate for genuinely missing glyphs

    // Keep a backup for the "at least 1" fallback
    let font_log_dists_backup: HashMap<usize, Vec<(f32, f32)>> = font_log_dists.clone();

    let mut scores: Vec<(String, f32)> = font_log_dists
        .into_iter()
        .filter_map(|(font_id, log_dists)| {
            let matched = log_dists.len();
            let name = index.font_names_table.get(font_id)?.clone();

            // Weighted mean of log-distances.
            let mut total_weight = 0.0_f32;
            let mut weighted_sum = 0.0_f32;
            for (ld, w) in &log_dists {
                weighted_sum += ld * w;
                total_weight += w;
            }

            // Penalty for genuinely missing glyphs (font can't render char).
            // After the second-pass backfill, this only fires when a font
            // truly lacks a glyph — not when it fell outside the search radius.
            for _ in matched..n_chars {
                weighted_sum += penalty_log_dist * 1.0;
                total_weight += 1.0;
            }

            let mean_log_dist = weighted_sum / total_weight.max(1e-9);
            // Negate so higher = better (smaller distance = better match)
            let score = -mean_log_dist;
            Some((name, score))
        })
        .collect();

    scores.retain(|(_, s)| s.is_finite());

    // OT variants (smcp, onum, salt, etc.) are treated as first-class fonts.
    // They produce genuinely different glyphs and should compete on merit.

    // Sort descending (higher = better = closer match)
    // Tiebreaker: prefer base (untagged) font over OT variants when scores
    // are equal — avoids random variant wins from floating-point noise.
    scores.sort_by(|a, b| {
        b.1.partial_cmp(&a.1)
            .unwrap_or(std::cmp::Ordering::Equal)
            .then_with(|| a.0.contains('|').cmp(&b.0.contains('|')))
    });

    // ── Cross-family Latin clone dedup ───────────────────────────────
    // Many font families embed the same Latin glyphs from a shared source.
    // E.g., ALL Noto* fonts (NotoSans, NotoSansDisplay, NotoTraditionalNushu,
    // NotoSansMath, NotoSansSymbols, etc.) share the same NotoSans Latin
    // outlines.  Font metrics (ascent/descent/em) differ, producing slightly
    // different feature-vector normalizations and scores (Δ ~0.01–0.03),
    // but the glyphs are identical.
    //
    // Two-pass dedup:
    //   1. Score-based: merge adjacent (sorted) entries within ε=1e-5 (exact clones)
    //   2. Path-based: group Noto sans-serif fonts into one family slot
    //
    // In each group, keep the entry with the best score.
    {
        // Pass 1: score-epsilon dedup
        let eps = 1e-5_f32;
        let mut deduped: Vec<(String, f32)> = Vec::new();
        for (name, score) in &scores {
            if let Some(last) = deduped.last_mut() {
                if (score - last.1).abs() < eps {
                    if name.len() < last.0.len() {
                        *last = (name.clone(), *score);
                    }
                    continue;
                }
            }
            deduped.push((name.clone(), *score));
        }
        scores = deduped;

        // Pass 2: Noto family grouping
        // All /noto/Noto* sans-serif fonts → "NotoSans" group
        // All /noto/NotoSerif* fonts → "NotoSerif" group
        // Keep best (highest score) per group; non-Noto fonts pass through.
        fn noto_group(name: &str) -> Option<&'static str> {
            // Match font paths containing "/noto/" or font names starting with "Noto"
            let is_noto = name.contains("/noto/") || {
                // Extract basename
                let base = name.rsplit('/').next().unwrap_or(name);
                base.starts_with("Noto")
            };
            if !is_noto { return None; }
            // Check serif vs sans
            let base = name.rsplit('/').next().unwrap_or(name);
            if base.starts_with("NotoSerif") {
                Some("__noto_serif__")
            } else if base.starts_with("NotoSansMono") || base.starts_with("NotoMono") {
                Some("__noto_mono__")
            } else {
                // Everything else: NotoSans*, NotoSansDisplay*, NotoTraditionalNushu*, etc.
                Some("__noto_sans__")
            }
        }

        let mut best_by_group: HashMap<&str, (usize, f32)> = HashMap::new();
        for (i, (name, score)) in scores.iter().enumerate() {
            if let Some(group) = noto_group(name) {
                let entry = best_by_group.entry(group).or_insert((i, *score));
                if *score > entry.1 {
                    *entry = (i, *score);
                }
            }
        }

        let mut drop_indices: std::collections::HashSet<usize> = std::collections::HashSet::new();
        for (_group, (keep_idx, _)) in &best_by_group {
            for (i, (name, _)) in scores.iter().enumerate() {
                if noto_group(name).is_some() && i != *keep_idx {
                    drop_indices.insert(i);
                }
            }
        }

        if !drop_indices.is_empty() {
            let before = scores.len();
            scores = scores.into_iter().enumerate()
                .filter(|(i, _)| !drop_indices.contains(i))
                .map(|(_, v)| v)
                .collect();
            eprintln!("  CI: Noto family dedup {before} → {} fonts", scores.len());
        }
    }

    // ── Statistical cutoff: keep best + near-ties ────────────────────
    // CI is the recall stage — high recall, lower precision (no spacing
    // info).  We keep the top score and anything within k·σ of it.
    //
    // σ is computed on the top 50 scores only (the contender pool), not
    // the full distribution.  The full distribution has a long left tail
    // of clearly-wrong fonts that inflates σ and makes the cutoff too
    // generous.  The top-50 σ measures spread among actual contenders.
    //
    // k = 0.5 * thoroughness: default thoroughness=1.0 → k=0.5.
    // Higher thoroughness widens the window (more candidates, slower).
    if scores.len() >= 2 {
        let top_n = 50.min(scores.len());
        let vals: Vec<f32> = scores.iter().take(top_n).map(|(_, s)| *s).collect();
        let n = vals.len() as f32;
        let mean = vals.iter().sum::<f32>() / n;
        let variance = vals.iter().map(|v| (v - mean).powi(2)).sum::<f32>() / n;
        let sigma = variance.sqrt();
        let best = vals[0];
        let k = 0.5 * thoroughness;
        let cutoff = best - k * sigma;
        let before = scores.len();
        scores.retain(|(_, s)| *s >= cutoff);
        eprintln!(
            "  CI sigma cutoff: best={:.3} top50_σ={:.3} cutoff={:.3} → {} of {} kept",
            best, sigma, cutoff, scores.len(), before,
        );
    }

    // Guarantee at least 1 result: if quorum dropped everything, return the
    // single font with the best (lowest) average distance across whatever
    // characters it did appear in.
    if scores.is_empty() && !font_log_dists_backup.is_empty() {
        if let Some(best) = font_log_dists_backup
            .into_iter()
            .filter_map(|(font_id, log_dists)| {
                let name = index.font_names_table.get(font_id)?.clone();
                let total_weight: f32 = log_dists.iter().map(|(_, w)| w).sum();
                let weighted_sum: f32 = log_dists.iter().map(|(ld, w)| ld * w).sum();
                let mean = weighted_sum / total_weight.max(1e-9);
                Some((name, -mean))
            })
            .max_by(|a, b| a.1.partial_cmp(&b.1).unwrap_or(std::cmp::Ordering::Equal))
        {
            scores.push(best);
        }
    }

    CiSearchResult { scores, char_detail }
}

/// Compute per-character squared Euclidean distances from crop features to a
/// specific font's reference glyphs.  Used after the winner is determined so
/// the audit log can include per-char scores for the chosen font.
///
/// Returns `(char, crop_index, dist_sq)` for each crop that has features and
/// a matching reference glyph in the index.  Crops with no features or no
/// reference for that font are omitted.
pub fn per_char_distances(
    index: &CharIndex,
    font_key: &str,
    char_crops: &[(char, &GrayImage)],
    classifier: &dyn crate::classifier::Classifier,
) -> Vec<(char, usize, f32)> {
    let precomputed: Vec<(usize, char, Vec<f32>)> = char_crops
        .iter()
        .enumerate()
        .filter_map(|(i, (c, img))| {
            compute_features(img).map(|f| (i, *c, classifier.prepare(*c, &f)))
        })
        .collect();
    per_char_distances_precomputed(index, font_key, &precomputed)
}

/// Like `per_char_distances` but takes precomputed embedded feature vectors.
/// Use this when computing distances against multiple fonts for the same crops
/// to avoid redundant `compute_features` calls.
pub fn per_char_distances_precomputed(
    index: &CharIndex,
    font_key: &str,
    crop_feats: &[(usize, char, Vec<f32>)],
) -> Vec<(char, usize, f32)> {
    // Find the font_id for the requested key
    let font_id = match index.font_names_table.iter().position(|n| n == font_key) {
        Some(id) => id,
        None => return Vec::new(),
    };

    let mut result = Vec::with_capacity(crop_feats.len());
    for (crop_idx, ch, ref query) in crop_feats {
        // Find this font's embedded vector for this character (O(1) lookup)
        if let Some(points) = index.flat_vecs.get(ch) {
            let ref_vec_opt = index.flat_vecs_font_idx.get(ch)
                .and_then(|idx_map| idx_map.get(&font_id))
                .map(|&idx| &points[idx].1);
            if let Some(ref_vec) = ref_vec_opt {
                let d2 = squared_distance(query, ref_vec);
                result.push((*ch, *crop_idx, d2));
            }
        }
    }
    result
}

/// Precompute embedded feature vectors for a set of character crops.
/// Returns `(crop_index, char, embedded_features)` for each crop that
/// produces valid features.
pub fn precompute_crop_features(
    char_crops: &[(char, &GrayImage)],
    classifier: &dyn crate::classifier::Classifier,
) -> Vec<(usize, char, Vec<f32>)> {
    char_crops
        .iter()
        .enumerate()
        .filter_map(|(i, (c, img))| {
            compute_features(img).map(|f| (i, *c, classifier.prepare(*c, &f)))
        })
        .collect()
}

