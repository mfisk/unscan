/// Bump this whenever the feature vector, normalization, or serialization
/// layout changes. Stale caches auto-rebuild on mismatch.
const INDEX_VERSION: u32 = 11;
const INDEX_MAGIC: &[u8; 4] = b"UCIX";

/// Save the character index to a binary file.
///
/// Format v5:
/// - [u8; 4]: magic bytes b"UCIX"
/// - u32: format version (4)
/// - u32: feature vector length (FEAT_LEN)
/// - u32: number of characters
/// - For each character:
///   - u32: char as u32
///   - u32: number of font entries
///   - For each entry:
///     - u32: font name length
///     - [u8]: font name bytes
///     - [f32; FEAT_LEN]: raw feature vector (unweighted)
///   - [f32; FEAT_LEN]: per-dimension σ values (computed from raw features)
/// - u32: number of skipped fonts
/// - For each skipped font:
///   - u32: name length
///   - [u8]: name bytes
pub fn save_index(index: &CharIndex, path: &Path) -> io::Result<()> {
    use std::io::Write;
    let mut buf = Vec::new();

    // Header
    buf.extend_from_slice(INDEX_MAGIC);
    buf.extend_from_slice(&INDEX_VERSION.to_le_bytes());
    buf.extend_from_slice(&(FEAT_LEN as u32).to_le_bytes());

    let n_chars = index.entries.len() as u32;
    buf.extend_from_slice(&n_chars.to_le_bytes());

    for (c, entries) in &index.entries {
        buf.extend_from_slice(&(*c as u32).to_le_bytes());
        buf.extend_from_slice(&(entries.len() as u32).to_le_bytes());
        for e in entries {
            let name_bytes = e.font_name.as_bytes();
            buf.extend_from_slice(&(name_bytes.len() as u32).to_le_bytes());
            buf.extend_from_slice(name_bytes);
            let feat = e.features.as_slice();
            for &v in feat.iter() {
                buf.extend_from_slice(&v.to_le_bytes());
            }
        }
        // Write per-dimension σ for this character (length-prefixed)
        let sigmas = index.dim_sigmas.get(c);
        let default_sigmas = vec![0.0f32; FEAT_LEN];
        let sigmas = sigmas.unwrap_or(&default_sigmas);
        buf.extend_from_slice(&(sigmas.len() as u32).to_le_bytes());
        for &s in sigmas.iter() {
            buf.extend_from_slice(&s.to_le_bytes());
        }
    }

    // Append skipped_fonts section
    buf.extend_from_slice(&(index.skipped_fonts.len() as u32).to_le_bytes());
    for name in &index.skipped_fonts {
        let name_bytes = name.as_bytes();
        buf.extend_from_slice(&(name_bytes.len() as u32).to_le_bytes());
        buf.extend_from_slice(name_bytes);
    }

    // Append font metadata section
    buf.extend_from_slice(&(index.font_meta.len() as u32).to_le_bytes());
    for (font_key, meta) in &index.font_meta {
        let key_bytes = font_key.as_bytes();
        buf.extend_from_slice(&(key_bytes.len() as u32).to_le_bytes());
        buf.extend_from_slice(key_bytes);

        let path_bytes = meta.path.to_string_lossy().as_bytes().to_vec();
        buf.extend_from_slice(&(path_bytes.len() as u32).to_le_bytes());
        buf.extend_from_slice(&path_bytes);

        let fam_bytes = meta.family_name.as_bytes();
        buf.extend_from_slice(&(fam_bytes.len() as u32).to_le_bytes());
        buf.extend_from_slice(fam_bytes);

        let ps_bytes = meta.postscript_name.as_bytes();
        buf.extend_from_slice(&(ps_bytes.len() as u32).to_le_bytes());
        buf.extend_from_slice(ps_bytes);

        let mut flags: u32 = 0;
        if meta.is_bold { flags |= 1; }
        if meta.is_italic { flags |= 2; }
        if meta.oldstyle_figures { flags |= 4; }
        flags |= (meta.class as u32) << 8;
        buf.extend_from_slice(&flags.to_le_bytes());

        let vtag_bytes = meta.variant_tag.as_bytes();
        buf.extend_from_slice(&(vtag_bytes.len() as u32).to_le_bytes());
        buf.extend_from_slice(vtag_bytes);

        if let Some(ref ovs) = meta.glyph_overrides {
            buf.extend_from_slice(&(ovs.len() as u32).to_le_bytes());
            for &(ch, gid) in ovs {
                buf.extend_from_slice(&(ch as u32).to_le_bytes());
                buf.extend_from_slice(&(gid as u32).to_le_bytes());
            }
        } else {
            buf.extend_from_slice(&0u32.to_le_bytes());
        }

        // Variations: count, then for each: 4-byte tag + f32 value
        if let Some(ref vars) = meta.variations {
            buf.extend_from_slice(&(vars.len() as u32).to_le_bytes());
            for (tag, val) in vars {
                buf.extend_from_slice(tag);
                buf.extend_from_slice(&val.to_le_bytes());
            }
        } else {
            buf.extend_from_slice(&0u32.to_le_bytes());
        }
    }

    let mut f = std::fs::File::create(path)?;
    f.write_all(&buf)?;
    Ok(())
}

/// Load a character index from a binary file.
pub fn load_index(path: &Path, classifier: &dyn crate::classifier::Classifier) -> io::Result<CharIndex> {
    use std::io::Read;
    let mut data = Vec::new();
    std::fs::File::open(path)?.read_to_end(&mut data)?;
    let mut pos;

    if data.len() < 12 {
        return Err(io::Error::new(io::ErrorKind::InvalidData, "index file too small"));
    }
    if &data[0..4] != INDEX_MAGIC {
        return Err(io::Error::new(io::ErrorKind::InvalidData,
            "stale index: missing magic header (pre-v2 format)"));
    }
    pos = 4;
    let version = u32::from_le_bytes(data[pos..pos+4].try_into().unwrap());
    pos += 4;
    if version != INDEX_VERSION {
        return Err(io::Error::new(io::ErrorKind::InvalidData,
            format!("stale index: version {version}, expected {INDEX_VERSION}")));
    }
    let feat_len = u32::from_le_bytes(data[pos..pos+4].try_into().unwrap());
    pos += 4;
    if feat_len as usize != FEAT_LEN {
        return Err(io::Error::new(io::ErrorKind::InvalidData,
            format!("stale index: feat_len {feat_len}, expected {FEAT_LEN}")));
    }

    let read_u32 = |pos: &mut usize| -> io::Result<u32> {
        if *pos + 4 > data.len() {
            return Err(io::Error::new(io::ErrorKind::UnexpectedEof, "truncated"));
        }
        let v = u32::from_le_bytes(data[*pos..*pos + 4].try_into().unwrap());
        *pos += 4;
        Ok(v)
    };
    let read_f32 = |pos: &mut usize| -> io::Result<f32> {
        if *pos + 4 > data.len() {
            return Err(io::Error::new(io::ErrorKind::UnexpectedEof, "truncated"));
        }
        let v = f32::from_le_bytes(data[*pos..*pos + 4].try_into().unwrap());
        *pos += 4;
        Ok(v)
    };

    let n_chars = read_u32(&mut pos)?;
    let mut entries: HashMap<char, Vec<FontCharEntry>> = HashMap::new();
    let mut dim_sigmas: HashMap<char, Vec<f32>> = HashMap::new();

    for _ in 0..n_chars {
        let c_u32 = read_u32(&mut pos)?;
        let c = char::from_u32(c_u32).ok_or_else(|| {
            io::Error::new(io::ErrorKind::InvalidData, "invalid char")
        })?;
        let n_fonts = read_u32(&mut pos)?;
        let mut font_entries = Vec::with_capacity(n_fonts as usize);

        for _ in 0..n_fonts {
            let name_len = read_u32(&mut pos)? as usize;
            if pos + name_len > data.len() {
                return Err(io::Error::new(io::ErrorKind::UnexpectedEof, "truncated name"));
            }
            let font_name = String::from_utf8_lossy(&data[pos..pos + name_len]).to_string();
            pos += name_len;

            let mut profile = [0.0f32; PROFILE_BINS];
            for p in &mut profile {
                *p = read_f32(&mut pos)?;
            }
            let aspect = read_f32(&mut pos)?;
            let ink_density = read_f32(&mut pos)?;
            let v_center = read_f32(&mut pos)?;
            let h_balance = read_f32(&mut pos)?;
            let serif_score = read_f32(&mut pos)?;
            let stroke_contrast = read_f32(&mut pos)?;
            let xh_cap_ratio = read_f32(&mut pos)?;

            // v2 features
            let counter_area_ratio = read_f32(&mut pos)?;
            let counter_centroid_x = read_f32(&mut pos)?;
            let counter_centroid_y = read_f32(&mut pos)?;
            let counter_aspect = read_f32(&mut pos)?;
            let mut terminal_angles = [0.0f32; TERMINAL_ANGLE_BINS];
            for t in &mut terminal_angles {
                *t = read_f32(&mut pos)?;
            }
            let ink_perimeter = read_f32(&mut pos)?;
            let compactness = read_f32(&mut pos)?;
            let mut h_crossings = [0.0f32; CROSSING_BINS];
            for hc in &mut h_crossings {
                *hc = read_f32(&mut pos)?;
            }

            // v3 features
            let mut row_profile = [0.0f32; ROW_PROFILE_BINS];
            for rp in &mut row_profile {
                *rp = read_f32(&mut pos)?;
            }
            let hole_count = read_f32(&mut pos)?;
            let h_symmetry = read_f32(&mut pos)?;
            let v_symmetry = read_f32(&mut pos)?;
            let skeleton_branch_pts = read_f32(&mut pos)?;
            let skeleton_end_pts = read_f32(&mut pos)?;
            let corner_count = read_f32(&mut pos)?;
            let mut quadrant_density = [0.0f32; 4];
            for qd in &mut quadrant_density {
                *qd = read_f32(&mut pos)?;
            }
            let mean_stroke_width = read_f32(&mut pos)?;

            font_entries.push(FontCharEntry {
                font_name,
                features: CharFeatures {
                    profile,
                    row_profile,
                    aspect,
                    ink_density,
                    v_center,
                    h_balance,
                    serif_score,
                    stroke_contrast,
                    xh_cap_ratio,
                    counter_area_ratio,
                    counter_centroid_x,
                    counter_centroid_y,
                    counter_aspect,
                    terminal_angles,
                    ink_perimeter,
                    compactness,
                    h_crossings,
                    hole_count,
                    h_symmetry,
                    v_symmetry,
                    skeleton_branch_pts,
                    skeleton_end_pts,
                    corner_count,
                    quadrant_density,
                    mean_stroke_width,
                },
            });
        }

        // Read per-dimension σ (length-prefixed)
        let sigma_len = read_u32(&mut pos)? as usize;
        let mut sigmas = vec![0.0f32; sigma_len];
        for s in &mut sigmas {
            *s = read_f32(&mut pos)?;
        }
        dim_sigmas.insert(c, sigmas);

        entries.insert(c, font_entries);
    }

    // Read skipped_fonts section
    let mut skipped_fonts = std::collections::HashSet::new();
    if pos < data.len() {
        if let Ok(n_skipped) = read_u32(&mut pos) {
            for _ in 0..n_skipped {
                let name_len = read_u32(&mut pos)? as usize;
                if pos + name_len > data.len() {
                    return Err(io::Error::new(io::ErrorKind::UnexpectedEof, "truncated skipped font name"));
                }
                let name = String::from_utf8_lossy(&data[pos..pos + name_len]).to_string();
                pos += name_len;
                skipped_fonts.insert(name);
            }
        }
    }

    // ── Read font metadata section ─────────────────────────────────
    let mut font_meta: HashMap<String, FontMeta> = HashMap::new();
    if pos < data.len() {
        if let Ok(n_meta) = read_u32(&mut pos) {
            for _ in 0..n_meta as usize {
                let key_len = read_u32(&mut pos)? as usize;
                if pos + key_len > data.len() {
                    return Err(io::Error::new(io::ErrorKind::UnexpectedEof, "truncated font meta key"));
                }
                let font_key = String::from_utf8_lossy(&data[pos..pos + key_len]).to_string();
                pos += key_len;

                let path_len = read_u32(&mut pos)? as usize;
                if pos + path_len > data.len() {
                    return Err(io::Error::new(io::ErrorKind::UnexpectedEof, "truncated font meta path"));
                }
                let path = std::path::PathBuf::from(String::from_utf8_lossy(&data[pos..pos + path_len]).to_string());
                pos += path_len;

                let fam_len = read_u32(&mut pos)? as usize;
                if pos + fam_len > data.len() {
                    return Err(io::Error::new(io::ErrorKind::UnexpectedEof, "truncated font meta family"));
                }
                let family_name = String::from_utf8_lossy(&data[pos..pos + fam_len]).to_string();
                pos += fam_len;

                let ps_len = read_u32(&mut pos)? as usize;
                if pos + ps_len > data.len() {
                    return Err(io::Error::new(io::ErrorKind::UnexpectedEof, "truncated font meta ps name"));
                }
                let postscript_name = String::from_utf8_lossy(&data[pos..pos + ps_len]).to_string();
                pos += ps_len;

                let flags = read_u32(&mut pos)?;
                let is_bold = (flags & 1) != 0;
                let is_italic = (flags & 2) != 0;
                let oldstyle_figures = (flags & 4) != 0;
                let class = ((flags >> 8) & 0xFF) as u8;

                let vtag_len = read_u32(&mut pos)? as usize;
                if pos + vtag_len > data.len() {
                    return Err(io::Error::new(io::ErrorKind::UnexpectedEof, "truncated font meta variant tag"));
                }
                let variant_tag = String::from_utf8_lossy(&data[pos..pos + vtag_len]).to_string();
                pos += vtag_len;

                let n_overrides = read_u32(&mut pos)? as usize;
                let glyph_overrides = if n_overrides > 0 {
                    let mut ovs = Vec::with_capacity(n_overrides);
                    for _ in 0..n_overrides {
                        let cp = read_u32(&mut pos)?;
                        let gid = read_u32(&mut pos)? as u16;
                        if let Some(ch) = char::from_u32(cp) {
                            ovs.push((ch, gid));
                        }
                    }
                    Some(ovs)
                } else {
                    None
                };

                // Variations (backward-compat: missing → None)
                let variations = if pos < data.len() {
                    match read_u32(&mut pos) {
                        Ok(n_vars) if n_vars > 0 => {
                            let n = n_vars as usize;
                            let mut vars = Vec::with_capacity(n);
                            for _ in 0..n {
                                if pos + 8 > data.len() { break; }
                                let mut tag = [0u8; 4];
                                tag.copy_from_slice(&data[pos..pos + 4]);
                                pos += 4;
                                let val = f32::from_le_bytes([
                                    data[pos], data[pos+1], data[pos+2], data[pos+3]
                                ]);
                                pos += 4;
                                vars.push((tag, val));
                            }
                            Some(vars)
                        }
                        _ => None,
                    }
                } else {
                    None
                };

                font_meta.insert(font_key, FontMeta {
                    path,
                    family_name,
                    postscript_name,
                    is_bold,
                    is_italic,
                    class,
                    variant_tag,
                    glyph_overrides,
                    oldstyle_figures,
                    variations,
                });
            }
        }
    }

    let mut index = CharIndex {
        entries,
        skipped_fonts,
        font_meta,
        font_names_table: Vec::new(),
        flat_vecs: HashMap::new(),
        dim_sigmas,
        flat_vecs_font_idx: HashMap::new(),
    };
    // Build flat vecs from loaded entries
    index.rebuild_vecs(classifier);
    Ok(index)
}

/// Read just the 12-byte header from a cached index file.
pub fn peek_header(path: &Path) -> io::Result<(u32, u32)> {
    use std::io::Read;
    let mut f = std::fs::File::open(path)?;
    let mut header = [0u8; 12];
    f.read_exact(&mut header)?;

    if &header[0..4] != INDEX_MAGIC {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            "missing UCIX magic header",
        ));
    }
    let version = u32::from_le_bytes(header[4..8].try_into().unwrap());
    let feat_len = u32::from_le_bytes(header[8..12].try_into().unwrap());
    Ok((version, feat_len))
}

/// Return the current expected version and feature length.
pub fn expected_header() -> (u32, u32) {
    (INDEX_VERSION, FEAT_LEN as u32)
}

/// Count the number of unique font names across all characters in the index.
pub fn count_fonts(index: &CharIndex) -> usize {
    index.font_names().len()
}

impl CharIndex {
    /// Collect all unique font names known to this index (both indexed and skipped).
    pub fn font_names(&self) -> std::collections::HashSet<String> {
        let mut names = self.skipped_fonts.clone();
        for entries in self.entries.values() {
            for e in entries {
                names.insert(e.font_name.clone());
            }
        }
        names
    }

    /// Collect only the font names that have actual indexed entries (not skipped).
    pub fn indexed_font_names(&self) -> std::collections::HashSet<String> {
        let mut names = std::collections::HashSet::new();
        for entries in self.entries.values() {
            for e in entries {
                names.insert(e.font_name.clone());
            }
        }
        names
    }

    /// Merge another index into this one.
    pub fn merge(&mut self, other: CharIndex, classifier: &dyn crate::classifier::Classifier) {
        for (c, new_entries) in other.entries {
            let existing = self.entries.entry(c).or_default();
            let existing_names: std::collections::HashSet<String> =
                existing.iter().map(|e| e.font_name.clone()).collect();
            for entry in new_entries {
                if !existing_names.contains(&entry.font_name) {
                    existing.push(entry);
                }
            }
        }
        self.skipped_fonts.extend(other.skipped_fonts);
        // Rebuild vecs after merge
        self.rebuild_vecs(classifier);
    }

    /// Remove all entries for the given font names.
    pub fn remove_fonts(&mut self, names: &std::collections::HashSet<String>, classifier: &dyn crate::classifier::Classifier) {
        for entries in self.entries.values_mut() {
            entries.retain(|e| !names.contains(&e.font_name));
        }
        self.skipped_fonts.retain(|n| !names.contains(n));
        // Rebuild vecs after removal
        self.rebuild_vecs(classifier);
    }

    /// Drop the raw `entries` HashMap to free memory after the index has been
    /// saved to disk.  Only `flat_vecs` (used for search) is kept.
    /// After compaction, `save_index` will no longer work — call this only once
    /// the index is persisted and you're entering the search/match phase.
    pub fn compact(&mut self) {
        self.entries.clear();
        self.entries.shrink_to_fit();
    }

    /// Number of indexed characters.
    pub fn n_chars(&self) -> usize {
        self.flat_vecs.len()
    }

    /// Total number of (deduplicated) font entries across all characters.
    pub fn n_entries(&self) -> usize {
        self.flat_vecs.values().map(|v| v.len()).sum()
    }
}
