/// Per-font feature for a single character.
#[derive(Debug, Clone)]
pub struct FontCharEntry {
    pub font_name: String,
    pub features: CharFeatures,
}

/// The full index: for each indexed character, a list of (font, features)
/// plus flat per-character vectors for brute-force spatial lookup.
#[derive(Debug)]
pub struct CharIndex {
    /// char → Vec<(font_name, features)> — raw entries for serialization + merge
    pub entries: HashMap<char, Vec<FontCharEntry>>,
    /// Fonts that were scanned but produced no indexable characters.
    pub skipped_fonts: std::collections::HashSet<String>,
    /// Per-font metadata (font_key → FontMeta). Serialized with the index
    /// so we can skip the filesystem font scan on warm runs.
    pub font_meta: HashMap<String, FontMeta>,
    /// Ordered font name table: font_id → font_name
    font_names_table: Vec<String>,
    /// Per-character flat vectors: (font_id, embedded_features) for brute-force search
    flat_vecs: HashMap<char, Vec<(usize, Vec<f32>)>>,
    /// Per-character per-dimension standard deviations (for diagnostics)
    dim_sigmas: HashMap<char, Vec<f32>>,
    /// Per-character font_id → index into flat_vecs for O(1) backfill lookup
    flat_vecs_font_idx: HashMap<char, HashMap<usize, usize>>,
}

impl CharIndex {
    /// Build flat per-character vectors and compute per-dimension σ from entries.
    pub fn rebuild_vecs(&mut self, classifier: &dyn crate::classifier::Classifier) {
        // Build font name → id mapping — collect unique names without
        // cloning every entry's font_name first.
        let mut name_set: std::collections::HashSet<&str> = std::collections::HashSet::new();
        for entries in self.entries.values() {
            for e in entries {
                name_set.insert(&e.font_name);
            }
        }
        let mut names: Vec<String> = name_set.into_iter().map(|s| s.to_string()).collect();
        names.sort();
        self.font_names_table = names;
        let name_to_id: HashMap<&str, usize> = self.font_names_table.iter()
            .enumerate()
            .map(|(i, n)| (n.as_str(), i))
            .collect();

        self.flat_vecs.clear();
        self.dim_sigmas.clear();

        let prep_dim = classifier.prepare_dim();

        for (c, char_entries) in &self.entries {
            if char_entries.is_empty() {
                continue;
            }

            let mut points: Vec<(usize, Vec<f32>)> = Vec::with_capacity(char_entries.len());

            for e in char_entries {
                let embedded = classifier.prepare(*c, &e.features);
                if let Some(&font_id) = name_to_id.get(e.font_name.as_str()) {
                    points.push((font_id, embedded));
                }
            }

            if points.is_empty() {
                continue;
            }

            // Compute per-dimension mean and σ
            let n = points.len() as f32;
            let mut means = vec![0.0f32; prep_dim];
            for (_, w) in &points {
                for d in 0..prep_dim {
                    means[d] += w[d];
                }
            }
            for d in 0..prep_dim {
                means[d] /= n;
            }

            let mut sigmas = vec![0.0f32; prep_dim];
            for (_, w) in &points {
                for d in 0..prep_dim {
                    let diff = w[d] - means[d];
                    sigmas[d] += diff * diff;
                }
            }
            for d in 0..prep_dim {
                sigmas[d] = (sigmas[d] / n).sqrt();
            }

            self.dim_sigmas.insert(*c, sigmas);
            let font_idx: HashMap<usize, usize> = points.iter()
                .enumerate()
                .map(|(idx, (fid, _))| (*fid, idx))
                .collect();
            self.flat_vecs.insert(*c, points);
            self.flat_vecs_font_idx.insert(*c, font_idx);
        }
    }

    /// Populate font_meta from a font catalog so the index can skip filesystem
    /// scans on warm runs.  Replaces any existing metadata.
    pub fn populate_font_meta(&mut self, catalog: &[crate::font_scan::FontEntry]) {
        for fe in catalog {
            let class_u8 = match fe.class {
                crate::font_scan::FontClass::Serif => 0,
                crate::font_scan::FontClass::Sans => 1,
                crate::font_scan::FontClass::Mono => 2,
                crate::font_scan::FontClass::Unknown => 3,
            };
            self.font_meta.insert(fe.font_key(), FontMeta {
                path: fe.path.clone(),
                family_name: fe.family_name.clone(),
                postscript_name: fe.postscript_name.clone(),
                is_bold: fe.is_bold,
                is_italic: fe.is_italic,
                class: class_u8,
                variant_tag: fe.variant_tag.clone(),
                glyph_overrides: fe.glyph_overrides.clone(),
                oldstyle_figures: fe.oldstyle_figures,
            });
        }
    }
}

/// Build the per-character index for all provided fonts.
/// Glyph override map for OT variant entries (e.g. smcp, onum).
/// Maps character → overridden glyph ID so the CI renders the correct variant glyph.
pub type GlyphOverrides = Option<Vec<(char, u16)>>;

/// Metadata for a single font entry (one per font_key in the catalog).
/// Stored in the char index so we can skip the filesystem scan on warm runs.
#[derive(Debug, Clone)]
pub struct FontMeta {
    pub path: std::path::PathBuf,
    pub family_name: String,
    pub postscript_name: String,
    pub is_bold: bool,
    pub is_italic: bool,
    pub class: u8, // 0=Serif, 1=Sans, 2=Mono, 3=Unknown
    pub variant_tag: String,
    pub glyph_overrides: GlyphOverrides,
    pub oldstyle_figures: bool,
}

/// Resolve glyph ID for a character, applying OT variant overrides when present.
/// Falls back to the font's default cmap lookup if no override exists for this character.
pub fn resolve_glyph<F: ab_glyph::Font>(font: &F, ch: char, overrides: Option<&[(char, u16)]>) -> ab_glyph::GlyphId {
    if let Some(ovs) = overrides {
        if let Some(&(_, gid)) = ovs.iter().find(|(c, _)| *c == ch) {
            return ab_glyph::GlyphId(gid);
        }
    }
    font.glyph_id(ch)
}

pub fn build_char_index(font_paths: &[(String, std::path::PathBuf, GlyphOverrides)], classifier: &dyn crate::classifier::Classifier) -> CharIndex {
    use rayon::prelude::*;

    let chars = indexed_chars();

    // Per-font result: Vec of (char, entry) pairs, plus font_name if skipped.
    struct FontResult {
        char_entries: Vec<(char, FontCharEntry)>,
        skipped: Option<String>,
    }

    // Phase 1: process each font in parallel (CPU-bound: render + features).
    // Font bytes are loaded from disk per-thread and dropped after processing,
    // so only ~N fonts are in memory at once (N = rayon thread count).
    let results: Vec<FontResult> = font_paths.par_iter().map(|(font_name, font_path, glyph_overrides)| {
        let font_data = match std::fs::read(font_path) {
            Ok(d) => d,
            Err(_) => {
                return FontResult {
                    char_entries: Vec::new(),
                    skipped: Some(font_name.clone()),
                };
            }
        };
        let font = match FontRef::try_from_slice(&font_data) {
            Ok(f) => f,
            Err(_) => {
                return FontResult {
                    char_entries: Vec::new(),
                    skipped: Some(font_name.clone()),
                };
            }
        };

        // Build fast lookup for glyph overrides
        let override_map: HashMap<char, u16> = glyph_overrides
            .as_ref()
            .map(|v| v.iter().cloned().collect())
            .unwrap_or_default();

        let xh_ratio = compute_xh_cap_ratio(&font);
        let serif = compute_font_serif_score(&font);

        let mut char_entries = Vec::with_capacity(chars.len());
        for &c in chars {
            // Use override glyph ID if this variant changes this character,
            // otherwise fall back to default glyph.
            let img = if let Some(&gid) = override_map.get(&c) {
                render_glyph_normalised(&font, ab_glyph::GlyphId(gid))
            } else {
                render_char_normalised(&font, c)
            };
            if let Some(img) = img {
                if let Some(mut feats) = compute_features(&img) {
                    feats.xh_cap_ratio = xh_ratio;
                    feats.serif_score = serif;
                    char_entries.push((c, FontCharEntry {
                        font_name: font_name.clone(),
                        features: feats,
                    }));
                }
            }
        }

        let skipped = if char_entries.is_empty() { Some(font_name.clone()) } else { None };
        FontResult { char_entries, skipped }
    }).collect();

    // Phase 2: merge results (sequential, fast — just moving Vecs)
    let mut entries: HashMap<char, Vec<FontCharEntry>> = HashMap::new();
    for c in chars {
        entries.insert(*c, Vec::with_capacity(font_paths.len()));
    }
    let mut skipped_fonts: std::collections::HashSet<String> = std::collections::HashSet::new();

    for result in results {
        if let Some(name) = result.skipped {
            skipped_fonts.insert(name);
        }
        for (c, entry) in result.char_entries {
            entries.entry(c).or_default().push(entry);
        }
    }

    let mut index = CharIndex {
        entries,
        skipped_fonts,
        font_meta: HashMap::new(),
        font_names_table: Vec::new(),
        flat_vecs: HashMap::new(),
        dim_sigmas: HashMap::new(),
        flat_vecs_font_idx: HashMap::new(),
    };
    index.rebuild_vecs(classifier);
    index
}

/// Render a single character in `font` at `NORM_H` ink height.
pub fn render_char_normalised<F: Font>(font: &F, c: char) -> Option<GrayImage> {
    render_glyph_normalised(font, font.glyph_id(c))
}

/// Render a specific glyph ID, normalised to NORM_H with tight ink crop.
pub fn render_glyph_normalised<F: Font>(font: &F, gid: ab_glyph::GlyphId) -> Option<GrayImage> {
    if gid.0 == 0 {
        return None;
    }

    let ref_h = 200.0f32;
    let ref_scale = PxScale::from(ref_h);
    let sf_ref = font.as_scaled(ref_scale);

    let glyph = gid.with_scale_and_position(ref_scale, point(0.0, sf_ref.ascent()));
    let outlined = font.outline_glyph(glyph)?;
    let bounds = outlined.px_bounds();
    let ink_h_ref = bounds.max.y - bounds.min.y;
    if ink_h_ref < 1.0 {
        return None;
    }

    let target_scale = ref_h * (NORM_H as f32 / ink_h_ref);
    let scale = PxScale::from(target_scale);
    let sf = font.as_scaled(scale);

    let glyph2 = gid.with_scale_and_position(scale, point(0.0, sf.ascent()));
    let outlined2 = font.outline_glyph(glyph2)?;
    let b2 = outlined2.px_bounds();

    let img_w = (b2.max.x - b2.min.x).ceil() as u32 + 2;
    let img_h = (b2.max.y - b2.min.y).ceil() as u32 + 2;
    if img_w == 0 || img_h == 0 || img_w > 500 || img_h > 500 {
        return None;
    }

    let mut canvas = GrayImage::from_pixel(img_w, img_h, Luma([255u8]));
    let ox = b2.min.x.floor() as i32;
    let oy = b2.min.y.floor() as i32;

    outlined2.draw(|gx, gy, cov| {
        let px = gx as i32 + (b2.min.x.floor() as i32) - ox + 1;
        let py = gy as i32 + (b2.min.y.floor() as i32) - oy + 1;
        if px >= 0 && py >= 0 && (px as u32) < img_w && (py as u32) < img_h {
            let val = (255.0 * (1.0 - cov)) as u8;
            let cur = canvas.get_pixel(px as u32, py as u32).0[0];
            canvas.put_pixel(px as u32, py as u32, Luma([cur.min(val)]));
        }
    });

    // Run through the same normalize path the scan side uses, so both
    // index-time and scan-time images have identical geometry (tight ink
    // crop, 1px padding, resized to exactly NORM_H).
    normalize_to_ink_bounds(&canvas)
}

// ---------------------------------------------------------------------------
// Shared normalisation: tight ink crop → NORM_H scale
// ---------------------------------------------------------------------------

pub fn normalize_to_ink_bounds(img: &GrayImage) -> Option<GrayImage> {
    let (w, h) = img.dimensions();
    if w == 0 || h == 0 {
        return None;
    }
    const THRESH: u8 = 200;
    let mut min_x = w;
    let mut max_x = 0u32;
    let mut min_y = h;
    let mut max_y = 0u32;
    for y in 0..h {
        for x in 0..w {
            if img.get_pixel(x, y).0[0] < THRESH {
                if x < min_x { min_x = x; }
                if x > max_x { max_x = x; }
                if y < min_y { min_y = y; }
                if y > max_y { max_y = y; }
            }
        }
    }
    if min_x > max_x || min_y > max_y {
        return None;
    }
    // Crop tightly to ink, then paste onto a white canvas with guaranteed
    // 1px padding on all sides — matching index-time render_char_normalised
    // which creates a canvas of (ink_w+2) × (ink_h+2).
    // Previous approach used saturating_sub which clipped at image boundary,
    // producing 0px padding when ink reached the edge of the raw slice.
    let ink_w = max_x - min_x + 1;
    let ink_h = max_y - min_y + 1;
    if ink_w < 1 || ink_h < 1 {
        return None;
    }
    let pad = 1u32;
    let canvas_w = ink_w + 2 * pad;
    let canvas_h = ink_h + 2 * pad;
    let mut canvas = GrayImage::from_pixel(canvas_w, canvas_h, Luma([255u8]));
    // Copy ink region into canvas at (pad, pad)
    for y in min_y..=max_y {
        for x in min_x..=max_x {
            let px = img.get_pixel(x, y);
            canvas.put_pixel(x - min_x + pad, y - min_y + pad, *px);
        }
    }
    let scaled_w = (canvas_w as f32 * NORM_H as f32 / canvas_h as f32).ceil() as u32;
    if scaled_w < 2 {
        return None;
    }
    Some(image::imageops::resize(
        &canvas,
        scaled_w,
        NORM_H,
        image::imageops::FilterType::Lanczos3,
    ))
}

