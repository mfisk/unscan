/// Feature weighting strategy for CI distance computation.
/// Toggle this to compare approaches; the compiler dead-code-eliminates unused paths.
#[allow(dead_code)]
#[derive(Clone, Copy)]
enum WeightMode {
    /// Per-group L2 normalization + group weights (0.40/0.30/0.30/0.30/0.20)
    GroupNorm,
    /// Per-dimension Fisher discriminant weights (sqrt(signal/noise), scale-adjusted)
    FisherPerDim,
}
const WEIGHT_MODE: WeightMode = WeightMode::FisherPerDim;

