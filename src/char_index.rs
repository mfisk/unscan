/// Search result from the character index for a single character.
/// Contains font candidates within the tolerance radius.
#[derive(Debug, Clone)]
pub struct CharSearchResult {
    /// The character queried
    pub ch: char,
    /// Candidate fonts within tolerance: (font_name, cosine_similarity)
    pub candidates: Vec<(String, f32)>,
    /// The search radius used
    pub radius: f32,
    /// Number of fonts within the radius
    pub n_within_radius: usize,
}

/// Search the index for candidate fonts matching the given character crops.
///
/// Two-stage pipeline:
///
/// 1. **Classify**: for each character crop, ask the classifier for the best
///    font match (ties allowed).  Union these per-crop picks into a candidate
///    set.
/// 2. **Score**: for each candidate font, compute the aggregate CI score
///    across *all* crops via `score_single_font` (geometric mean of per-char
///    distances).  Rank by aggregate score.
///
/// This replaces the former radius-search / quality-gate / backfill pipeline.
/// The classifier is the authority on per-character font identity; the
/// aggregation only combines those verdicts across characters.
///
/// Returns ranked font scores + per-character CI detail for audit.

/// Per-character CI detail, collected from the search_candidates loop.
#[derive(Debug, Clone)]
pub struct CharCiDetail {
    pub ch: char,
    pub crop_index: usize,
    pub best_prob: f32,
    pub passed_gate: bool,
    /// Top-3 fonts by probability (name, prob), highest first.
    pub nearest: Vec<(String, f32)>,
    /// When the OCR correction gate fires, the original OCR character
    /// that was replaced.  `ch` then holds the corrected character,
    /// and `nearest`/`best_prob` reflect the corrected char's CI.
    pub ocr_corrected_from: Option<char>,
    /// Best alternative character considered (even if correction gate
    /// didn't fire).  Always the char with the highest probability among
    /// all confusables/alternatives tested, if any were tested.
    pub best_alt_char: Option<char>,
    /// Distance of the best alternative character.
    pub best_alt_dist: Option<f32>,
}

/// Result of `search_candidates`: ranked font scores + per-character CI detail.
#[derive(Debug)]
pub struct CiSearchResult {
    pub scores: Vec<(String, f32)>,
    pub char_detail: Vec<CharCiDetail>,
}

pub fn search_candidates(
    index: &CharIndex,
    char_crops: &[(char, GrayImage)],
    _thoroughness: f32,
    _audit: bool,
    classifier: &dyn crate::classifier::Classifier,
) -> CiSearchResult {
    if char_crops.is_empty() {
        return CiSearchResult { scores: Vec::new(), char_detail: Vec::new() };
    }

    // ── Pre-compute features ────────────────────────────────────────
    let crop_data: Vec<(usize, char, CharFeatures)> = char_crops
        .iter()
        .enumerate()
        .filter_map(|(i, (c, img))| {
            let mut f = compute_features(img)?;
            f.raster = Some(img.clone());
            Some((i, *c, f))
        })
        .collect();

    if crop_data.is_empty() {
        return CiSearchResult { scores: Vec::new(), char_detail: Vec::new() };
    }

    let n_chars = crop_data.len();

    // ── Stage 1: per-crop classification ────────────────────────────
    // For each crop, the classifier picks the best font(s).
    // Union all picks into the candidate set.
    let mut candidate_set: HashSet<usize> = HashSet::new();
    let mut char_detail: Vec<CharCiDetail> = Vec::with_capacity(n_chars);

    for &(crop_idx, ch, ref raw_feat) in &crop_data {
        // Classifier picks top fonts — it owns the font vectors internally
        let picks = classifier.classify(ch, raw_feat, 3);
        if picks.is_empty() {
            continue;
        }

        for &(font_id, _prob) in &picks {
            candidate_set.insert(font_id);
        }

        let best_prob = picks.iter()
            .map(|(_, p)| *p)
            .fold(0.0f32, f32::max);

        let nearest: Vec<(String, f32)> = picks.iter()
            .take(3)
            .filter_map(|(id, p)| {
                Some((index.font_names_table.get(*id)?.clone(), *p))
            })
            .collect();

        char_detail.push(CharCiDetail {
            ch,
            crop_index: crop_idx,
            best_prob,
            passed_gate: true,
            nearest,
            ocr_corrected_from: None,
            best_alt_char: None,
            best_alt_dist: None,
        });
    }

    if candidate_set.is_empty() {
        return CiSearchResult { scores: Vec::new(), char_detail };
    }

    // ── Stage 2: score each candidate across all crops ──────────────
    let mut scores: Vec<(String, f32)> = candidate_set.iter()
        .filter_map(|&font_id| {
            let name = index.font_names_table.get(font_id)?.clone();
            let score = score_single_font_via_classifier(
                classifier, font_id, &crop_data,
            )?;
            Some((name, score))
        })
        .collect();

    scores.retain(|(_, s)| s.is_finite());

    // Sort descending (higher = better = closer match).
    // Tiebreaker: prefer base (untagged) font over OT variants.
    scores.sort_by(|a, b| {
        b.1.partial_cmp(&a.1)
            .unwrap_or(std::cmp::Ordering::Equal)
            .then_with(|| a.0.contains('|').cmp(&b.0.contains('|')))
    });

    // No candidate pruning — SSIM is the real arbiter.

    CiSearchResult { scores, char_detail }
}

