/// Search result from the character index for a single character.
/// Contains font candidates within the tolerance radius.
#[derive(Debug, Clone)]
pub struct CharSearchResult {
    /// The character queried
    pub ch: char,
    /// Candidate fonts within tolerance: (font_name, cosine_similarity)
    pub candidates: Vec<(String, f32)>,
    /// The search radius used
    pub radius: f32,
    /// Number of fonts within the radius
    pub n_within_radius: usize,
}

/// Search the index for candidate fonts matching the given character crops.
///
/// Two-stage pipeline:
///
/// 1. **Classify**: for each character crop, ask the classifier for the best
///    font match (ties allowed).  Union these per-crop picks into a candidate
///    set.
/// 2. **Score**: for each candidate font, compute the aggregate CI score
///    across *all* crops via `score_single_font` (geometric mean of per-char
///    distances).  Rank by aggregate score.
///
/// This replaces the former radius-search / quality-gate / backfill pipeline.
/// The classifier is the authority on per-character font identity; the
/// aggregation only combines those verdicts across characters.
///
/// Returns ranked font scores + per-character CI detail for audit.

/// Per-character CI detail, collected from the search_candidates loop.
#[derive(Debug, Clone)]
pub struct CharCiDetail {
    pub ch: char,
    pub crop_index: usize,
    pub min_dist_sq: f32,
    pub passed_gate: bool,
    /// Top-3 nearest fonts (name, dist_sq).
    pub nearest: Vec<(String, f32)>,
    /// When the OCR correction gate fires, the original OCR character
    /// that was replaced.  `ch` then holds the corrected character,
    /// and `nearest`/`min_dist_sq` reflect the corrected char's CI.
    pub ocr_corrected_from: Option<char>,
    /// Best alternative character considered (even if correction gate
    /// didn't fire).  Always the char with the lowest distance among
    /// all confusables/alternatives tested, if any were tested.
    pub best_alt_char: Option<char>,
    /// Distance of the best alternative character.
    pub best_alt_dist: Option<f32>,
}

/// Result of `search_candidates`: ranked font scores + per-character CI detail.
#[derive(Debug)]
pub struct CiSearchResult {
    pub scores: Vec<(String, f32)>,
    pub char_detail: Vec<CharCiDetail>,
}

pub fn search_candidates(
    index: &CharIndex,
    char_crops: &[(char, GrayImage)],
    thoroughness: f32,
    audit: bool,
    classifier: &dyn crate::classifier::Classifier,
) -> CiSearchResult {
    if char_crops.is_empty() {
        return CiSearchResult { scores: Vec::new(), char_detail: Vec::new() };
    }

    // ── Pre-compute features ────────────────────────────────────────
    // Keep both raw CharFeatures (for classifier.classify) and projected
    // vectors (for score_single_font in stage 2).
    let crop_data: Vec<(usize, char, CharFeatures, Vec<f32>)> = char_crops
        .iter()
        .enumerate()
        .filter_map(|(i, (c, img))| {
            compute_features(img).map(|f| {
                let projected = classifier.prepare(*c, &f);
                (i, *c, f, projected)
            })
        })
        .collect();

    if crop_data.is_empty() {
        return CiSearchResult { scores: Vec::new(), char_detail: Vec::new() };
    }

    let n_chars = crop_data.len();

    // ── Stage 1: per-crop classification ────────────────────────────
    // For each crop, the classifier picks the best font(s) (ties allowed).
    // Union all picks into the candidate set.  Also collect per-char audit
    // detail (top-3 nearest) via a lightweight distance scan.
    let mut candidate_set: HashSet<usize> = HashSet::new();
    let mut char_detail: Vec<CharCiDetail> = Vec::with_capacity(n_chars);

    for &(crop_idx, ch, ref raw_feat, ref _projected) in &crop_data {
        let points = match index.flat_vecs.get(&ch) {
            Some(p) if !p.is_empty() => p,
            _ => continue,
        };

        // Classifier picks the best font(s) — black box, ties allowed
        let picks = classifier.classify(ch, raw_feat, points);
        for &(font_id, _dist) in &picks {
            candidate_set.insert(font_id);
        }

        let min_dist_sq = picks.iter()
            .map(|(_, d)| *d)
            .fold(f32::INFINITY, f32::min);

        // Audit: top-3 nearest fonts by distance.
        // The classify call already scanned all points internally;
        // for audit we need the top-3, so do a quick partial sort.
        let nearest: Vec<(String, f32)> = if audit {
            // Compute distances to all fonts for this char to get top-3
            let projected = &crop_data.iter()
                .find(|(ci, _, _, _)| *ci == crop_idx)
                .unwrap().3;
            let mut dists: Vec<(usize, f32)> = points.iter()
                .map(|(id, ref_vec)| (*id, squared_distance(projected, ref_vec)))
                .collect();
            dists.sort_by(|a, b| a.1.partial_cmp(&b.1).unwrap_or(std::cmp::Ordering::Equal));
            dists.iter()
                .take(3)
                .filter_map(|(id, d)| {
                    Some((index.font_names_table.get(*id)?.clone(), *d))
                })
                .collect()
        } else {
            // Non-audit: just report the pick(s)
            picks.iter()
                .take(3)
                .filter_map(|(id, d)| {
                    Some((index.font_names_table.get(*id)?.clone(), *d))
                })
                .collect()
        };

        char_detail.push(CharCiDetail {
            ch,
            crop_index: crop_idx,
            min_dist_sq,
            passed_gate: true, // no gate in new pipeline
            nearest,
            ocr_corrected_from: None,
            best_alt_char: None,
            best_alt_dist: None,
        });
    }

    if candidate_set.is_empty() {
        return CiSearchResult { scores: Vec::new(), char_detail };
    }

    // ── Stage 2: score each candidate across all crops ──────────────
    // Use score_single_font which computes the geometric-mean aggregate
    // of per-char distances (same formula as before, applied to the full
    // crop set for each candidate font).
    let crop_feats: Vec<(usize, char, Vec<f32>)> = crop_data.iter()
        .map(|(i, c, _, proj)| (*i, *c, proj.clone()))
        .collect();

    let mut scores: Vec<(String, f32)> = candidate_set.iter()
        .filter_map(|&font_id| {
            let name = index.font_names_table.get(font_id)?.clone();
            let score = score_single_font(index, &name, &crop_feats)?;
            Some((name, score))
        })
        .collect();

    scores.retain(|(_, s)| s.is_finite());

    // Sort descending (higher = better = closer match).
    // Tiebreaker: prefer base (untagged) font over OT variants.
    scores.sort_by(|a, b| {
        b.1.partial_cmp(&a.1)
            .unwrap_or(std::cmp::Ordering::Equal)
            .then_with(|| a.0.contains('|').cmp(&b.0.contains('|')))
    });

    // ── Cross-family Latin clone dedup ───────────────────────────────
    {
        // Pass 1: score-epsilon dedup
        let eps = 1e-5_f32;
        let mut deduped: Vec<(String, f32)> = Vec::new();
        for (name, score) in &scores {
            if let Some(last) = deduped.last_mut() {
                if (score - last.1).abs() < eps {
                    if name.len() < last.0.len() {
                        *last = (name.clone(), *score);
                    }
                    continue;
                }
            }
            deduped.push((name.clone(), *score));
        }
        scores = deduped;

        // Pass 2: Noto family grouping
        fn noto_group(name: &str) -> Option<&'static str> {
            let is_noto = name.contains("/noto/") || {
                let base = name.rsplit('/').next().unwrap_or(name);
                base.starts_with("Noto")
            };
            if !is_noto { return None; }
            let base = name.rsplit('/').next().unwrap_or(name);
            if base.starts_with("NotoSerif") {
                Some("__noto_serif__")
            } else if base.starts_with("NotoSansMono") || base.starts_with("NotoMono") {
                Some("__noto_mono__")
            } else {
                Some("__noto_sans__")
            }
        }

        let mut best_by_group: HashMap<&str, (usize, f32)> = HashMap::new();
        for (i, (name, score)) in scores.iter().enumerate() {
            if let Some(group) = noto_group(name) {
                let entry = best_by_group.entry(group).or_insert((i, *score));
                if *score > entry.1 {
                    *entry = (i, *score);
                }
            }
        }

        let mut drop_indices: HashSet<usize> = HashSet::new();
        for (_group, (keep_idx, _)) in &best_by_group {
            for (i, (name, _)) in scores.iter().enumerate() {
                if noto_group(name).is_some() && i != *keep_idx {
                    drop_indices.insert(i);
                }
            }
        }

        if !drop_indices.is_empty() {
            scores = scores.into_iter().enumerate()
                .filter(|(i, _)| !drop_indices.contains(i))
                .map(|(_, v)| v)
                .collect();
        }
    }

    // ── Statistical cutoff: keep best + near-ties ────────────────────
    if scores.len() >= 2 {
        let top_n = 50.min(scores.len());
        let vals: Vec<f32> = scores.iter().take(top_n).map(|(_, s)| *s).collect();
        let n = vals.len() as f32;
        let mean = vals.iter().sum::<f32>() / n;
        let variance = vals.iter().map(|v| (v - mean).powi(2)).sum::<f32>() / n;
        let sigma = variance.sqrt();
        let best = vals[0];
        let k = 0.5 * thoroughness;
        let cutoff = best - k * sigma;
        scores.retain(|(_, s)| *s >= cutoff);
    }

    CiSearchResult { scores, char_detail }
}

/// Compute per-character squared Euclidean distances from crop features to a
/// specific font's reference glyphs.  Used after the winner is determined so
/// the audit log can include per-char scores for the chosen font.
///
/// Returns `(char, crop_index, dist_sq)` for each crop that has features and
/// a matching reference glyph in the index.  Crops with no features or no
/// reference for that font are omitted.
pub fn per_char_distances(
    index: &CharIndex,
    font_key: &str,
    char_crops: &[(char, &GrayImage)],
    classifier: &dyn crate::classifier::Classifier,
) -> Vec<(char, usize, f32)> {
    let precomputed: Vec<(usize, char, Vec<f32>)> = char_crops
        .iter()
        .enumerate()
        .filter_map(|(i, (c, img))| {
            compute_features(img).map(|f| (i, *c, classifier.prepare(*c, &f)))
        })
        .collect();
    per_char_distances_precomputed(index, font_key, &precomputed)
}

/// Like `per_char_distances` but takes precomputed embedded feature vectors.
/// Use this when computing distances against multiple fonts for the same crops
/// to avoid redundant `compute_features` calls.
pub fn per_char_distances_precomputed(
    index: &CharIndex,
    font_key: &str,
    crop_feats: &[(usize, char, Vec<f32>)],
) -> Vec<(char, usize, f32)> {
    // Find the font_id for the requested key
    let font_id = match index.font_names_table.iter().position(|n| n == font_key) {
        Some(id) => id,
        None => return Vec::new(),
    };

    let mut result = Vec::with_capacity(crop_feats.len());
    for (crop_idx, ch, ref query) in crop_feats {
        // Find this font's embedded vector for this character (O(1) lookup)
        if let Some(points) = index.flat_vecs.get(ch) {
            let ref_vec_opt = index.flat_vecs_font_idx.get(ch)
                .and_then(|idx_map| idx_map.get(&font_id))
                .map(|&idx| &points[idx].1);
            if let Some(ref_vec) = ref_vec_opt {
                let d2 = squared_distance(query, ref_vec);
                result.push((*ch, *crop_idx, d2));
            }
        }
    }
    result
}

/// For each character crop, compute the 1-based rank of `font_key` among all
/// fonts for that character, sorted by squared Euclidean distance (1 = closest).
/// Returns `(crop_index, rank)` for each crop where the font is present.
pub fn gt_font_ranks(
    index: &CharIndex,
    font_key: &str,
    crop_feats: &[(usize, char, Vec<f32>)],
    char_crops: &[(char, &GrayImage)],
    classifier: &dyn crate::classifier::Classifier,
) -> std::collections::HashMap<usize, usize> {
    let font_id = match index.font_names_table.iter().position(|n| n == font_key) {
        Some(id) => id,
        None => return std::collections::HashMap::new(),
    };
    let mut result = std::collections::HashMap::new();
    for (crop_idx, ch, _projected) in crop_feats {
        if let Some(points) = index.flat_vecs.get(ch) {
            // Check the font is present for this char
            if index.flat_vecs_font_idx.get(ch)
                .and_then(|m| m.get(&font_id)).is_none() {
                continue;
            }
            // Find the crop image for this character
            let raw_feat = if let Some((_, img)) = char_crops.get(*crop_idx) {
                match compute_features(img) {
                    Some(f) => f,
                    None => continue,
                }
            } else {
                continue;
            };
            // Use the classifier's own ranking — same ordering it uses
            // for font selection.  No direct access to projected vectors.
            let ranked = classifier.rank(*ch, &raw_feat, points);
            let mut rank = 0usize;
            for (fid, _score) in ranked {
                rank += 1;
                if fid == font_id {
                    result.insert(*crop_idx, rank);
                    break;
                }
            }
        }
    }
    result
}

