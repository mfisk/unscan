/// Detect whether a glyph image shows serifs.
fn detect_serif(img: &GrayImage) -> f32 {
    let (w, h) = img.dimensions();
    if w < 3 || h < 8 {
        return 0.0;
    }

    let threshold = 200u8;
    let mut row_ink = vec![0u32; h as usize];
    let mut min_y = h;
    let mut max_y = 0u32;

    for y in 0..h {
        let mut count = 0u32;
        for x in 0..w {
            if img.get_pixel(x, y).0[0] < threshold {
                count += 1;
            }
        }
        row_ink[y as usize] = count;
        if count > 0 {
            if y < min_y { min_y = y; }
            if y > max_y { max_y = y; }
        }
    }

    let ink_h = max_y.saturating_sub(min_y) + 1;
    if ink_h < 8 {
        return 0.0;
    }

    let terminal_rows = (ink_h / 8).max(2).min(4);

    let top_ink: f32 = (min_y..min_y + terminal_rows)
        .map(|y| row_ink[y as usize] as f32)
        .sum::<f32>() / terminal_rows as f32;
    let bot_ink: f32 = ((max_y + 1 - terminal_rows)..=max_y)
        .map(|y| row_ink[y as usize] as f32)
        .sum::<f32>() / terminal_rows as f32;

    let mid_start = min_y + ink_h / 3;
    let mid_end = min_y + 2 * ink_h / 3;
    let mid_rows = (mid_end - mid_start).max(1);
    let mid_ink: f32 = (mid_start..mid_end)
        .map(|y| row_ink[y as usize] as f32)
        .sum::<f32>() / mid_rows as f32;

    if mid_ink < 1.0 {
        return 0.0;
    }

    let top_ratio = top_ink / mid_ink;
    let bot_ratio = bot_ink / mid_ink;
    let avg_ratio = (top_ratio + bot_ratio) / 2.0;

    ((avg_ratio - 1.0)).clamp(0.0, 1.0)
}

/// Compute the expected pixel gap between the ink of character `a` and the ink
/// of character `b` when typeset adjacently at `scale`.  Returns RSB(a) + LSB(b)
/// in pixels, i.e. the whitespace the font places between the two glyphs'
/// ink bounding boxes.  Returns 0.0 when either glyph has no outline.

/// Return the ink width of a glyph in pixels from outline bounds (no rasterization).
pub fn font_ink_width<F: Font>(font: &F, scale: PxScale, ch: char) -> Option<f32> {
    let gid = font.glyph_id(ch);
    let glyph = gid.with_scale_and_position(scale, point(0.0, 0.0));
    let outlined = font.outline_glyph(glyph)?;
    let b = outlined.px_bounds();
    Some(b.max.x - b.min.x)
}

/// Return the expected ink-to-ink gap between two adjacent glyphs from outline bounds.
pub fn font_pair_ink_gap<F: Font>(font: &F, scale: PxScale, ch_a: char, ch_b: char) -> f32 {
    let sf = font.as_scaled(scale);
    let gid_a = font.glyph_id(ch_a);
    let gid_b = font.glyph_id(ch_b);
    let adv_a = sf.h_advance(gid_a);

    let glyph_a = gid_a.with_scale_and_position(scale, point(0.0, 0.0));
    let glyph_b = gid_b.with_scale_and_position(scale, point(0.0, 0.0));

    let outlined_a = match font.outline_glyph(glyph_a) {
        Some(o) => o,
        None => return 0.0,
    };
    let outlined_b = match font.outline_glyph(glyph_b) {
        Some(o) => o,
        None => return 0.0,
    };

    let bounds_a = outlined_a.px_bounds();
    let bounds_b = outlined_b.px_bounds();

    // gap = advance_a - ink_right_a + ink_left_b
    (adv_a - bounds_a.max.x + bounds_b.min.x).max(0.0)
}

/// Compute a per-font serif confidence score.
pub fn compute_font_serif_score<F: Font>(font: &F) -> f32 {
    let diag_chars = ['I', 'l'];
    let mut scores = Vec::new();

    for &c in &diag_chars {
        if let Some(img) = render_char_normalised(font, c) {
            let s = detect_serif(&img);
            scores.push(s);
        }
    }

    if scores.is_empty() {
        return 0.0;
    }

    let sum: f32 = scores.iter().sum();
    (sum / scores.len() as f32).clamp(0.0, 1.0)
}

/// Measure stroke contrast (thick-to-thin ratio) from a glyph image.
/// Collect all horizontal and vertical ink run lengths (≥2px) from a binarized glyph.
fn collect_ink_runs(img: &GrayImage) -> Vec<u32> {
    let (w, h) = img.dimensions();
    let threshold = 200u8;
    let mut all_runs: Vec<u32> = Vec::new();

    for y in 0..h {
        let mut run = 0u32;
        for x in 0..w {
            if img.get_pixel(x, y).0[0] < threshold {
                run += 1;
            } else {
                if run >= 2 { all_runs.push(run); }
                run = 0;
            }
        }
        if run >= 2 { all_runs.push(run); }
    }

    for x in 0..w {
        let mut run = 0u32;
        for y in 0..h {
            if img.get_pixel(x, y).0[0] < threshold {
                run += 1;
            } else {
                if run >= 2 { all_runs.push(run); }
                run = 0;
            }
        }
        if run >= 2 { all_runs.push(run); }
    }

    all_runs
}

fn measure_stroke_contrast(img: &GrayImage) -> f32 {
    let (w, h) = img.dimensions();
    if w < 4 || h < 4 {
        return 1.0;
    }

    let all_runs = collect_ink_runs(img);
    if all_runs.len() < 4 {
        return 1.0;
    }

    let mut sorted = all_runs;
    sorted.sort_unstable();
    let p10 = sorted[sorted.len() / 10].max(1);
    let p90 = sorted[sorted.len() * 9 / 10].max(1);

    p90 as f32 / p10 as f32
}

/// Mean stroke width normalised by image height.
///
/// Captures absolute stroke heaviness — the main signal that distinguishes
/// weight classes (Light 300 / Regular 400 / Medium 500 / Bold 700).
/// `stroke_contrast` captures the *ratio* of thick-to-thin strokes, which is
/// similar across weights of the same family; `mean_stroke_width` captures the
/// actual thickness.
fn measure_mean_stroke_width(img: &GrayImage) -> f32 {
    let (w, h) = img.dimensions();
    if w < 4 || h < 4 {
        return 0.0;
    }

    let all_runs = collect_ink_runs(img);
    if all_runs.is_empty() {
        return 0.0;
    }

    let sum: f64 = all_runs.iter().map(|&r| r as f64).sum();
    let mean = sum / all_runs.len() as f64;

    // Normalise by image height so the feature is scale-invariant
    (mean / h as f64) as f32
}

/// Compute x-height / cap-height ratio for a font.
pub fn compute_xh_cap_ratio<F: Font>(font: &F) -> f32 {
    let scale = PxScale::from(200.0);

    let ink_height_at_scale = |c: char| -> Option<f32> {
        let gid = font.glyph_id(c);
        if gid.0 == 0 { return None; }
        let sf = font.as_scaled(scale);
        let glyph = gid.with_scale_and_position(scale, point(0.0, sf.ascent()));
        let outlined = font.outline_glyph(glyph)?;
        let b = outlined.px_bounds();
        let ih = b.max.y - b.min.y;
        if ih > 0.5 { Some(ih) } else { None }
    };

    match (ink_height_at_scale('x'), ink_height_at_scale('H')) {
        (Some(xh), Some(ch)) if ch > 0.0 => (xh / ch).clamp(0.0, 1.0),
        _ => 0.65,
    }
}

/// Aggregate per-char weighted log-distances into a single overall CI score.
/// Used by both `search_candidates` and `score_single_font` — one formula,
/// one implementation.  Higher = better (smaller distance = better match).
fn aggregate_ci_score(log_dists: &[(f32, f32)], n_total_chars: usize) -> f32 {
    // Missing glyph penalty.  A font that can't render a character is a
    // categorical failure, not a distance calculation.  Infinite penalty
    // ensures it can never win regardless of how well other characters match.
    const MISSING_GLYPH_PENALTY: f32 = f32::INFINITY;

    let matched = log_dists.len();
    let mut total_weight = 0.0_f32;
    let mut weighted_sum = 0.0_f32;
    for &(ld, w) in log_dists {
        weighted_sum += ld * w;
        total_weight += w;
    }
    for _ in matched..n_total_chars {
        weighted_sum += MISSING_GLYPH_PENALTY * 1.0;
        total_weight += 1.0;
    }
    let mean_log_dist = weighted_sum / total_weight.max(1e-9);
    -mean_log_dist
}

/// Compute the overall CI score for a single font, using the same aggregation
/// as `search_candidates`.  Returns `None` if the font has no indexed chars
/// matching the crops.
pub fn score_single_font(
    index: &CharIndex,
    font_key: &str,
    crop_feats: &[(usize, char, Vec<f32>)],
) -> Option<f32> {
    let dists = per_char_distances_precomputed(index, font_key, crop_feats);
    if dists.is_empty() {
        return None;
    }
    let log_dists: Vec<(f32, f32)> = dists
        .iter()
        .map(|(ch, _, d2)| ((*d2 + 1e-10_f32).ln(), char_weight(*ch)))
        .collect();
    let score = aggregate_ci_score(&log_dists, crop_feats.len());
    if score.is_finite() { Some(score) } else { None }
}

/// Character discriminativeness weight for scoring.
fn char_weight(c: char) -> f32 {
    match c {
        'g' | 'a' | 'e' | 'R' | 'Q' | 'G' | 'S' | 'f' | 't' | 'y' | '&' | '@' => 1.5,
        'I' | 'l' | '1' | '|' | '!' | '.' | ',' | ':' | ';' | '-' => 0.5,
        'b' | 'd' | 'p' | 'q' | 'n' | 'u' | 'o' | 'c' | 'O' | 'C' | 'D' => 0.8,
        'k' | 'w' | 'x' | 'z' | 'A' | 'B' | 'E' | 'F' | 'K' | 'M' | 'N' | 'W' => 1.2,
        // Ligatures — highly discriminative (font either has the glyph or doesn't)
        '\u{FB00}' | '\u{FB01}' | '\u{FB02}' | '\u{FB03}' | '\u{FB04}' => 2.0,
        _ => 1.0,
    }
}

